"""Fontes do golden set: import dos ``seed`` de ``evals/`` e cenários sintéticos.

* **seed** — um caso de ``evals/*.json`` é lido de volta para as entradas dos
  builders (candidatos, resumo, semente de ``shuffle``): o texto do ``state`` é
  analisado (independente dos builders) e a semente é procurada uma única vez.
  Se o conteúdo do eval não mudou, o bloco ``build`` já guardado é reutilizado,
  de modo que uma mudança de **prompt** nunca altera os casos (só o lock);
* **synthetic** — um cenário de ``scenarios.json`` (spec compacta de um
  ``GameState`` + regra de segurança) passa pelos builders reais e a etiqueta
  JEV-A é derivada pela regra (:mod:`golden_rules`).
"""
from __future__ import annotations

import hashlib
import json
import math
import re
from pathlib import Path
from typing import Any, Mapping

from golden_core import (
    MAX_SEED_SEARCH, SEED_FILES, action_candidates, call_builder as _call_builder, canonical_json,
    rebuild_request, snapshot_from_spec,
)
from golden_rules import RuleContext, RuleError, bands_for, derive_action_labels
from system_one_dwarf.game.models import GameState

__all__ = ["import_seed_case", "scenario_to_case", "build_sources"]

_CASE_KEYS = ("id", "source", "group", "role", "rule", "tags", "notes", "origin", "twin",
              "build", "expected", "bands", "band_ceiling")


_ACTION_LINE = re.compile(r"^(?P<id>\S+) — \[A(?P<n>\d+)\] (?P<rest>.*)$")
_CAND_LINE = re.compile(r"^\[C(?P<n>\d+)\] (?P<rest>.*)$")
_EVENT_LINE = re.compile(r"^(\d+)\. (.*)$")
_ACTION_SEP = "\n\nAVAILABLE ACTIONS (generated by code; ids are exact):\n"


def _questions_without_guard(questions: Mapping[str, Any]) -> dict[str, Any]:
    return {k: dict(v) for k, v in questions.items() if k != "has_injection"}


def _seed_inputs(role: str, case: Mapping[str, Any]) -> tuple[str, dict[str, Any], dict[str, Any]]:
    """``(builder, inputs, options)`` lidos do ``state`` de um caso de ``evals/``."""
    state = str(case["state"])
    questions = case["questions"]
    ordering = case.get("ordering") or {}
    if role == "JEV-A":
        head, sep, tail = state.partition(_ACTION_SEP)
        if not sep or not head.startswith("SITUATION SUMMARY: "):
            raise ValueError("state is not in the build_action format")
        actions = []
        for line in tail.splitlines():
            match = _ACTION_LINE.match(line)
            if not match:
                raise ValueError(f"unreadable action line: {line!r}")
            name, has_desc, desc = match["rest"].partition(": ")
            actions.append({"id": match["id"], "name": name, "description": desc if has_desc else ""})
        return "build_action", {"action_candidates": actions,
                                "state_summary": head[len("SITUATION SUMMARY: "):]}, {}
    if role == "JEV-D":
        match = re.match(
            r"^CONTEXT:\n(?P<ctx>.*)\n\nACTION CONFIDENCE \(computed by code; do not re-estimate\): "
            r"(?P<c>.*)$", state, re.S)
        if not match:
            raise ValueError("state is not in the build_doubt format")
        text = match["c"]
        if text.startswith("unavailable (the model"):
            confidence: float | None = None
        elif text.startswith("unavailable (reported"):
            confidence = 0.0
        else:
            confidence = float(text)
        return "build_doubt", {"context": match["ctx"], "action_confidence": confidence}, {}
    if role == "JEV-M":
        match = re.match(
            r"^NARRATIVE TAIL \(rolling narrative, most recent last\):\n(?P<nar>.*?)\n\n"
            r"(?:RECENT EVENTS[^\n]*:\n(?P<ev>.*))?$", state, re.S)
        if not match:
            raise ValueError("state is not in the build_memory format")
        events = [m[2] for m in (_EVENT_LINE.match(l) for l in (match["ev"] or "").splitlines()) if m]
        return "build_memory", {"recent_events": events, "narrative_tail": match["nar"]}, {}
    if role == "JEV-R":
        match = re.match(
            r"^SITUATION: (?P<sit>.*?)\n\nKNOWLEDGE CANDIDATES \(retrieved top-\d+, indexed\):\n"
            r"(?P<rest>.*)$", state, re.S)
        if not match:
            raise ValueError("state is not in the build_retrieval format")
        labels = case.get("candidate_labels") or {}
        candidates = []
        for line in match["rest"].splitlines():
            row = _CAND_LINE.match(line)
            if not row or f"C{row['n']}" not in labels:
                raise ValueError(f"unreadable candidate line: {line!r}")
            title, has_summary, summary = row["rest"].partition(" | ")
            candidates.append({"id": labels[f"C{row['n']}"], "title": title,
                               "summary": summary if has_summary else ""})
        theme = questions.get("dominant_theme")
        inputs: dict[str, Any] = {"candidates": candidates, "situation": match["sit"]}
        if isinstance(theme, Mapping):
            inputs["themes"] = [k for k in theme["criteria"] if k != "other"]
        else:
            inputs["include_theme_choice"] = False
        return "build_retrieval", inputs, {}
    raise ValueError(f"unknown role {role!r}")


def _order_key(role: str) -> str:
    return {"JEV-A": "action", "JEV-D": "question_format", "JEV-R": "dominant_theme"}.get(role, "")


def _find_seed(builder: str, inputs: Mapping[str, Any], role: str, case: Mapping[str, Any]) -> int | None:
    """Semente de ``shuffle`` que reproduz a ordem congelada do caso (busca determinística)."""
    key = _order_key(role)
    want = (case.get("ordering") or {}).get(key)
    if not key or not want:
        return None
    try:
        canonical = _call_builder(builder, inputs, {"shuffle_seed": 0})["ordering"].get(key)
    except Exception:
        return None
    if not isinstance(canonical, list) or sorted(map(str, canonical)) != sorted(map(str, want)):
        return None  # a ordem congelada nem é uma permutação das opções: nenhuma semente a dá
    shuffled = max(1, len(want) - 1)  # a opção de saída fica fixa no fim
    limit = min(MAX_SEED_SEARCH, max(2_000, 20 * math.factorial(min(shuffled, 9))))
    for seed in range(limit):
        try:
            got = _call_builder(builder, inputs, {"shuffle_seed": seed})["ordering"].get(key)
        except Exception:
            return None
        if got == want:
            return seed
    return None


def _import_build(role: str, case: Mapping[str, Any]) -> dict[str, Any]:
    """Bloco ``build`` de um seed: entradas dos builders + semente, ou pedido congelado.

    Reconstrói o pedido com os builders e confirma que bate com o ``state`` e
    as ``questions`` do ficheiro; se não bater, guarda o pedido ``frozen``
    (sem regressão de prompt, mas ainda com integridade e etiquetas).
    """
    questions = case["questions"]
    guard = isinstance(questions.get("has_injection"), Mapping)
    try:
        builder, inputs, options = _seed_inputs(role, case)
        options = dict(options)
        frozen_order = bool(_order_key(role) and (case.get("ordering") or {}).get(_order_key(role)))
        if frozen_order:
            seed = _find_seed(builder, inputs, role, case)
            if seed is None:
                raise ValueError("no shuffle seed reproduces the frozen option order")
            options["shuffle_seed"] = seed
        elif builder != "build_memory":  # sem ordem congelada: opções na ordem canónica
            options["shuffle"] = False
        rebuilt = _call_builder(builder, inputs, options)
        if rebuilt["state"] != case["state"] or canonical_json(
            {k: dict(v) for k, v in rebuilt["questions"].items()}
        ) != canonical_json(_questions_without_guard(questions)):
            raise ValueError("rebuilt request differs from the stored one")
        return {"kind": "inputs", "builder": builder, "inputs": inputs, "options": options,
                "guard": guard}
    except Exception:  # noqa: BLE001 - qualquer falha de reconstrução ⇒ pedido congelado
        return {"kind": "frozen", "guard": False,
                "request": {"state": case["state"],
                            "questions": {k: dict(v) for k, v in questions.items()}}}


def import_seed_case(stem: str, case: Mapping[str, Any], *,
                     known: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Um caso de ``evals/*.json`` → caso golden ``source=seed`` (com ``origin`` + hash do original).

    ``known`` é o caso golden já guardado: se o conteúdo do eval não mudou
    (``origin.sha256``), o seu bloco ``build`` é **reutilizado** tal e qual.
    Assim a regeneração não depende dos builders actuais — uma mudança de
    prompt aparece como ``prompt-drift`` (blessable), nunca como ``build-drift``.
    """
    name = str(case["name"])
    role = str(case["role"])
    origin = {"file": f"{stem}.json", "name": name, "sha256": hashlib.sha256(canonical_json(
        {"state": case["state"], "questions": case["questions"], "expected": case.get("expected")}
    ).encode("utf-8")).hexdigest()}
    reusable = (
        isinstance(known, Mapping) and isinstance(known.get("origin"), Mapping)
        and known["origin"].get("sha256") == origin["sha256"] and isinstance(known.get("build"), Mapping)
    )
    build = json.loads(canonical_json(known["build"])) if reusable else _import_build(role, case)  # type: ignore[index]
    baseline = case.get("baseline")
    clean_name = str(baseline) if baseline else name
    tags = [f"role={role}", "source=seed", f"file={stem}"]
    if stem == "injection-evals":
        tags.append("injection")
    return {
        "id": f"seed-{name}", "source": "seed", "group": f"pair-{clean_name}" if stem == "injection-evals" else None,
        "role": role, "rule": None, "tags": tags, "notes": str(case.get("notes") or ""),
        "origin": origin, "twin": f"seed-{baseline}" if baseline else None,
        "build": build, "expected": dict(case.get("expected") or {}),
        "bands": dict(case.get("bands") or {}), "band_ceiling": case.get("band_ceiling"),
    }


def _case_dict(**fields: Any) -> dict[str, Any]:
    return {key: fields.get(key) for key in _CASE_KEYS}


def scenario_to_case(scenario: Mapping[str, Any]) -> dict[str, Any]:
    """Um cenário de ``scenarios.json`` → caso golden ``source=synthetic`` (labels por regra)."""
    sid = str(scenario["id"])
    role = str(scenario["role"])
    rule = scenario.get("rule")
    snapshot = snapshot_from_spec(scenario.get("state") or {})
    builder = {"JEV-A": "build_action", "JEV-R": "build_retrieval",
               "JEV-M": "build_memory", "JEV-D": "build_doubt"}[role]
    build: dict[str, Any] = {
        "kind": "state", "builder": builder, "snapshot": snapshot,
        "objective": str(scenario.get("objective") or ""),
        "guard": bool(scenario.get("guard", False)),
    }
    for key in ("blocked", "knowledge", "narrative_tail", "action_confidence"):
        if key in scenario:
            build[key] = scenario[key]
    if "knowledge" in build:  # ``relevant`` é só o rótulo do cenário, não entra no prompt
        build["knowledge"] = [{k: v for k, v in item.items() if k != "relevant"}
                              for item in build["knowledge"]]
    guard_value = bool(scenario.get("injected", False))
    expected: dict[str, Any]
    bands: dict[str, str]
    if role == "JEV-A":
        state = GameState.from_dict(snapshot)
        ctx = RuleContext(state=state, candidates=action_candidates(build, state),
                          objective=build["objective"], blocked=tuple(build.get("blocked") or ()))
        try:
            expected = derive_action_labels(str(rule), ctx)
        except RuleError as exc:
            raise ValueError(f"{sid}: rule {rule!r} does not apply: {exc}") from None
        bands = bands_for(expected["action"])
    elif role == "JEV-R":
        names = [n for n in rebuild_request({"id": sid, "build": build})["questions"]
                 if n.startswith("include_")]
        knowledge = list(build.get("knowledge") or [])
        include = scenario.get("expected_include") or {}
        if len(names) != len(knowledge) or set(include) != {k["id"] for k in knowledge}:
            raise ValueError(f"{sid}: expected_include must label every knowledge candidate")
        expected = {name: bool(include[item["id"]]) for name, item in zip(names, knowledge)}
        if scenario.get("dominant_theme"):
            expected["dominant_theme"] = str(scenario["dominant_theme"])
        bands = {name: "auto" for name in expected}
    else:
        expected = dict(scenario["expected"])
        bands = dict(scenario.get("bands") or {k: "auto" for k in expected})
    if build["guard"]:
        expected["has_injection"] = guard_value
        bands["has_injection"] = "auto"
    tags = [f"role={role}", "source=synthetic"] + ([f"rule={rule}"] if rule else [])
    tags += [str(t) for t in scenario.get("tags", [])]
    return _case_dict(
        id=sid, source="synthetic", group=scenario.get("group"), role=role, rule=rule, tags=tags,
        notes=str(scenario.get("notes") or ""), twin=scenario.get("twin"), build=build,
        expected=expected, bands=bands,
        band_ceiling="hitl" if guard_value else None,
    )


def build_sources(evals_dir: Path, scenarios_path: Path, *,
                  known: Mapping[str, Mapping[str, Any]] | None = None) -> list[dict[str, Any]]:
    """Todos os casos, regenerados das fontes (``evals/*.json`` + ``scenarios.json``).

    ``known`` (id → caso guardado) evita refazer a procura de sementes dos
    seeds cujo eval não mudou (ver :func:`import_seed_case`).
    """
    cases: list[dict[str, Any]] = []
    for filename in SEED_FILES:
        path = evals_dir / filename
        for raw in json.loads(path.read_text(encoding="utf-8")):
            cases.append(import_seed_case(path.stem, raw, known=(known or {}).get(f"seed-{raw['name']}")))
    if scenarios_path.exists():
        data = json.loads(scenarios_path.read_text(encoding="utf-8"))
        for scenario in data.get("scenarios", []):
            cases.append(scenario_to_case(scenario))
    return sorted(cases, key=lambda case: case["id"])
